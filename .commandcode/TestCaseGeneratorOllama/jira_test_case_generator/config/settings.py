"""Configuration loading and persistence.

Precedence, highest first:
1. An explicit ``APP_ENV_FILE`` environment variable.
2. A ``.env`` file discovered from the application directory upwards.
3. Environment variables already present in the process.
4. Optional Streamlit secrets.

Settings are never hard-coded in source. The Jira API token is masked
everywhere it could be displayed or logged.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Dict, Optional

from models.data_models import AppSettings

APP_DIR = Path(__file__).resolve().parent.parent
ENV_FILENAME = ".env"
_SEARCH_LIMIT = 5

# Logical setting -> accepted environment variable names. Matching is
# case-insensitive and ignores spaces/underscores so keys such as
# "Ollama url" are recognised.
_ENV_CANDIDATES: Dict[str, tuple] = {
    "jira_base_url": ("JIRA_BASE_URL", "JIRA_URL", "JIRA_HOST"),
    "jira_email": ("JIRA_EMAIL", "JIRA_USER", "JIRA_USERNAME"),
    "jira_token": ("JIRA_TOKEN", "JIRA_API_KEY", "JIRA_API_TOKEN"),
    "ollama_url": ("OLLAMA_URL", "Ollama url", "OLLAMA_BASE_URL", "OLLAMA_HOST"),
    "ollama_model": ("OLLAMA_MODEL",),
}

# Canonical keys used when writing the file back to disk.
_CANONICAL_KEYS = {
    "jira_base_url": "JIRA_BASE_URL",
    "jira_email": "JIRA_EMAIL",
    "jira_token": "JIRA_TOKEN",
    "ollama_url": "OLLAMA_URL",
    "ollama_model": "OLLAMA_MODEL",
}


def _normalize_key(key: str) -> str:
    return re.sub(r"[\s_]+", "", key).lower()


def _read_env_file(path: Path) -> Dict[str, str]:
    """Parse a simple KEY=VALUE file, tolerating spaces in keys."""
    values: Dict[str, str] = {}
    try:
        content = path.read_text(encoding="utf-8")
    except OSError:
        return values

    for raw_line in content.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key:
            values[_normalize_key(key)] = value
    return values


def discover_env_file() -> Optional[Path]:
    """Locate the ``.env`` file used for configuration, if one exists."""
    override = os.environ.get("APP_ENV_FILE")
    if override:
        candidate = Path(override).expanduser()
        return candidate if candidate.is_file() else None

    current = APP_DIR
    for _ in range(_SEARCH_LIMIT):
        candidate = current / ENV_FILENAME
        if candidate.is_file():
            return candidate
        if current.parent == current:
            break
        current = current.parent
    return None


def env_file_for_writing() -> Path:
    """Path settings are persisted to (the application-local ``.env``)."""
    return APP_DIR / ENV_FILENAME


def _streamlit_secrets() -> Dict[str, str]:
    try:
        import streamlit as st  # imported lazily; optional dependency path

        secrets = st.secrets
        return {str(k): str(v) for k, v in secrets.items()}
    except Exception:
        return {}


def _collect(*sources: Dict[str, str]) -> Dict[str, str]:
    """Merge normalized key/value sources; earlier sources win."""
    merged: Dict[str, str] = {}
    for source in sources:
        for key, value in source.items():
            norm = _normalize_key(key)
            if norm and norm not in merged:
                merged[norm] = value
    return merged


def load_settings() -> AppSettings:
    """Build an :class:`AppSettings` from all available configuration sources."""
    env_file = discover_env_file()
    file_values = _read_env_file(env_file) if env_file else {}
    process_values = _collect(dict(os.environ))
    secret_values = _collect(_streamlit_secrets())

    values = _collect(file_values, process_values, secret_values)

    settings = AppSettings()
    for attribute, candidates in _ENV_CANDIDATES.items():
        for candidate in candidates:
            found = values.get(_normalize_key(candidate))
            if found:
                setattr(settings, attribute, found)
                break
    return settings


def save_settings(settings: AppSettings) -> Path:
    """Persist settings to the application-local ``.env`` file."""
    path = env_file_for_writing()
    lines = [
        "# Generated by the Jira Test Case Generator Settings screen.",
        "# Credentials are stored locally and never transmitted elsewhere.",
    ]
    for attribute, canonical in _CANONICAL_KEYS.items():
        lines.append(f"{canonical}={getattr(settings, attribute) or ''}")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    for attribute, canonical in _CANONICAL_KEYS.items():
        os.environ[canonical] = getattr(settings, attribute) or ""

    return path


def reset_settings_file() -> bool:
    """Delete the application-local settings file. Returns True if removed."""
    path = env_file_for_writing()
    if path.is_file():
        path.unlink()
        return True
    return False


def current_env_file() -> Optional[Path]:
    """The file configuration was actually read from (for display)."""
    return discover_env_file()
